// Extract the released basic-duel rules without executing HTML or copying its DOM UI.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const source = '合掌网页版-正式版本存档/合掌网页版v2.5.8.2.html';
const html = fs.readFileSync(path.join(root, source), 'utf8');
function section(start, end) {
  const a = html.indexOf(start), b = html.indexOf(end, a);
  if (a < 0 || b <= a) throw new Error('正式版代码边界发生变化，请检查后更新抽取器：' + start);
  return html.slice(a, b).trim();
}
const combat = section('const MOVES = {', '/* js/skills.js */');
const energy = section('function basicRoundShouldReset(', 'function runBasicEnergyChecks(')
  .replace('skillMove(moveKey)', 'MOVES[moveKey]');
const result = '// Generated by tools/sync-wechat-core.cjs. Do not edit.\n' +
  '// Source: ' + source + '\n// SHA256: ' + crypto.createHash('sha256').update(html).digest('hex') + '\n' +
  combat + '\n\n' + energy + '\n\nmodule.exports = { MOVES, MOVE_KEYS, resolveDuelCombat, basicRoundShouldReset, basicEnergyAfterRound };\n';
const target = path.join(root, 'wechat-minigame/js/core.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== result) throw new Error('微信基础规则需要重新同步');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, result);
}
console.log('微信基础规则已' + (process.argv.includes('--check') ? '核对' : '同步'));
